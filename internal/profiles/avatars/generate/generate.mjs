// Generates the bundled profile avatars (SVG), catalog.json and LICENSES.md.
//
//   cd internal/profiles/avatars/generate && npm ci && npm run generate
//
// Only styles whose definition declares CC0 1.0, or CC BY 4.0 (then the entry
// carries the attribution text, shown by the clients and in LICENSES.md), are
// accepted. The licence, creator and source are read from each definition's
// `meta` block, so the catalog always matches what DiceBear ships. Never add
// fan art or images from streaming services here.
import { Avatar } from '@dicebear/core';
import { createRequire } from 'node:module';
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, '..');
const filesDir = join(outDir, 'files');

const pkgVersion = (name) => JSON.parse(readFileSync(join(here, 'node_modules', name, 'package.json'), 'utf8')).version;
const STYLES_VERSION = pkgVersion('@dicebear/styles');
const CORE_VERSION = pkgVersion('@dicebear/core');
const ALLOWED_LICENSES = ['CC0 1.0', 'CC BY 4.0'];
const needsAttribution = (license) => license.startsWith('CC BY');

const backgrounds = ['b6e3f4', 'c0aede', 'd1d4f9', 'ffd5dc', 'ffdfbf', 'c1f0d1'];

// [style, category, label prefix, seeds]
const sets = [
  ['lorelei', 'characters', 'Lorelei', ['Aiko', 'Haru', 'Mei', 'Ren', 'Sora', 'Yuki', 'Kaito', 'Nami']],
  ['notionists', 'characters', 'Notionist', ['Akira', 'Hana', 'Kenji', 'Rin', 'Taro', 'Emi']],
  ['critters', 'creatures', 'Critter', ['Mochi', 'Dango', 'Kuro', 'Shiro', 'Tama', 'Pochi']],
  ['thumbs', 'fun', 'Thumbs', ['Ichi', 'Ni', 'San', 'Yon']],
  // Phase 4: more variety. Appended so the ids above never change.
  ['open-peeps', 'characters', 'Peep', ['Daichi', 'Kana', 'Shin', 'Yua']],
  ['adventurer', 'characters', 'Adventurer', ['Hikari', 'Jun', 'Momo', 'Riku', 'Saki', 'Yuto']],
  ['pixel-art', 'retro', 'Pixel', ['Koji', 'Nao', 'Kai', 'Aya']],
  ['voxel-bot', 'retro', 'Bot', ['Robo', 'Gear', 'Volt', 'Bolt']],
  ['clay', 'creatures', 'Clay', ['Puni', 'Mugi', 'Kibi', 'Azuki']],
  ['sprouts', 'fun', 'Sprout', ['Midori', 'Hana', 'Take', 'Ume']],
  ['planets', 'space', 'Planet', ['Hoshi', 'Tsuki', 'Kasei', 'Dosei']],
];

rmSync(filesDir, { recursive: true, force: true });
mkdirSync(filesDir, { recursive: true });

const catalog = [];
const licenses = new Map();

for (const [style, category, labelPrefix, seeds] of sets) {
  const definition = require(`@dicebear/styles/${style}.json`);
  const meta = definition.meta ?? {};
  if (!ALLOWED_LICENSES.includes(meta.license?.name)) {
    throw new Error(`style ${style} has licence ${meta.license?.name}, only ${ALLOWED_LICENSES.join(' / ')} are allowed`);
  }
  if (needsAttribution(meta.license.name) && !(meta.license.text && meta.creator?.name)) {
    throw new Error(`style ${style} is ${meta.license.name} but has no attribution text or creator`);
  }
  const sourceUrl = `https://github.com/dicebear/styles/blob/v${STYLES_VERSION}/src/${style}.json`;
  licenses.set(style, { meta, sourceUrl });

  seeds.forEach((seed, i) => {
    const id = `gl-${style}-${String(i + 1).padStart(2, '0')}`;
    const svg = new Avatar(definition, {
      seed: `garceslab-${seed}`,
      size: 256,
      backgroundColor: [backgrounds[i % backgrounds.length]],
      title: `${labelPrefix} ${seed}`,
    }).toString();
    const file = `${id}.svg`;
    writeFileSync(join(filesDir, file), svg + '\n');
    const entry = {
      id,
      file,
      category,
      label: `${labelPrefix} ${seed}`,
      license: meta.license.name,
      licenseUrl: meta.license.url,
      creator: meta.creator?.name ?? '',
      source: sourceUrl,
      origin: meta.source?.url ?? '',
    };
    if (needsAttribution(meta.license.name)) {
      entry.attribution = meta.license.text;
    }
    catalog.push(entry);
  });
}

writeFileSync(join(outDir, 'catalog.json'), JSON.stringify(catalog, null, 2) + '\n');

let md = `# Profile avatar licences\n\n`;
md += `Generated by \`generate/generate.mjs\` with @dicebear/core ${CORE_VERSION} and @dicebear/styles ${STYLES_VERSION}.\n`;
md += `Only styles declared as CC0 1.0 or CC BY 4.0 in their definition are used. CC0 needs no attribution,\n`;
md += `but it is given here anyway. CC BY 4.0 styles are credited below, in catalog.json (\`attribution\`)\n`;
md += `and in the avatar pickers. The DiceBear code itself is MIT. Avatars are used unmodified, as\n`;
md += `generated by DiceBear from the seeds in generate.mjs.\n\n`;
md += `| Style | Licence | Artist | Original design | Definition |\n|---|---|---|---|---|\n`;
for (const [style, { meta, sourceUrl }] of licenses) {
  md += `| ${meta.source?.name ?? style} | [${meta.license.name}](${meta.license.url}) | [${meta.creator?.name}](${meta.creator?.url}) | ${meta.source?.url ?? ''} | ${sourceUrl} |\n`;
}
md += `\nLicence texts as declared by each style:\n\n`;
for (const [, { meta }] of licenses) md += `- ${meta.license.text}\n`;
writeFileSync(join(outDir, 'LICENSES.md'), md);

console.log(`wrote ${catalog.length} avatars (${readdirSync(filesDir).length} files)`);
